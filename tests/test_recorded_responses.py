FIXTURE_DIR = Path(__file__).parent / "fixtures" / "mal"


def load(name: str):
    text = (FIXTURE_DIR / name).read_text(encoding="utf-8")
    return json.loads(text) if name.endswith(".json") else text


def _user_list_fixture(tool: str) -> str:
    # The fake user name in the file name is chosen by the anonymiser.
    [path] = FIXTURE_DIR.glob(f"{tool}_user_*.json")
    return path.name


def _user_name(fixture: str) -> str:
    return fixture.rsplit("_user_", 1)[1].removesuffix(".json")


