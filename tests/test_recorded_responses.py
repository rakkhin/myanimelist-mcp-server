def test_manga_authors_carry_names():
    details = load("get_manga_details_100035.json")["authors"]
    ranked = [
        author
        for item in load("get_manga_ranking.json")["data"]
        for author in item["node"]["authors"]
    ]

    for author in details + ranked:
        assert author["node"]["first_name"] or author["node"]["last_name"]


